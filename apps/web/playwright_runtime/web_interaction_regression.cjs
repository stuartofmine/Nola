// Run against the isolated ui_review_fixture.py server after build:interaction-tests.
const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
    const browser = await chromium.launch({...require('./test_environment.cjs').browserOptions(), headless: true});
    const page = await browser.newPage({viewport: {width: 600, height: 800}});
    const resize = async size => {
        await page.setViewportSize(size);
        await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    };
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    try {
        await page.goto(`${process.env.UI_FIXTURE_URL || 'http://127.0.0.1:5129'}/review-tests/tests/interaction.html`);
        const summary = page.locator('.model-menu summary');
        await summary.focus(); await page.keyboard.press('ArrowDown');
        assert.equal(await page.locator('.choices button').first().evaluate(e => e === document.activeElement), true);
        await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
        assert.equal(await page.locator('#choice').textContent(), 'one');
        assert.equal(await summary.evaluate(e => e === document.activeElement), true);
        await page.keyboard.press('ArrowUp');
        assert.equal(await page.locator('.choices a').evaluate(e => e === document.activeElement), true);
        await page.keyboard.press('Escape');
        assert.equal(await summary.evaluate(e => e === document.activeElement), true);
        await page.locator('#error').click();
        assert.equal(await page.locator('.model-menu').evaluate(e => e.open), false, 'error must not steal focus or open menu');
        await summary.click(); await page.locator('#after').focus();
        await page.waitForFunction(() => !document.querySelector('.model-menu').open);
        assert.equal(await page.locator('.model-menu').evaluate(e => e.open), false, 'tabbing away dismisses menu');
        await resize({width: 1000, height: 800});
        await page.locator('#after').focus();
        await resize({width: 600, height: 800});
        assert.equal(await page.locator('dialog').evaluate(e => e.open), false, 'passive sidebar must not become modal on resize');
        assert.equal(await page.locator('#after').evaluate(e => e === document.activeElement), true);
        await page.locator('#panel-opener').click();
        await page.locator('#panel-draft').fill('Keep my draft');
        await page.keyboard.press('Escape');
        assert.equal(await page.locator('#panel-opener').evaluate(e => e === document.activeElement), true);
        await page.locator('#panel-opener').click();
        assert.equal(await page.locator('#panel-draft').inputValue(), 'Keep my draft');
        await resize({width: 1000, height: 800});
        await page.locator('#panel-draft').focus();
        await resize({width: 600, height: 800});
        assert.equal(await page.locator('dialog').evaluate(e => e.open && e.matches(':modal')), true);
        assert.equal(await page.locator('#panel-draft').inputValue(), 'Keep my draft');
        assert.equal(await page.locator('dialog').evaluate(e => e.contains(document.activeElement)), true, 'modal must own focus after breakpoint');
        await page.emulateMedia({reducedMotion: 'reduce'});
        assert.equal(await page.locator('dialog').evaluate(e => getComputedStyle(e).animationName), 'none');
        await page.keyboard.press('Escape');
        await summary.click();
        assert.equal(await page.locator('.choices').evaluate(e => getComputedStyle(e).animationName), 'none');
        await page.emulateMedia({reducedMotion: 'no-preference'});
        assert.notEqual(await page.locator('.choices').evaluate(e => getComputedStyle(e).animationName), 'none');
        await page.keyboard.press('Escape');
        // Rapid reopen during entrance animation remains interactive.
        await page.locator('#panel-opener').click(); await page.keyboard.press('Escape');
        await page.locator('#panel-opener').click(); await page.locator('#panel-draft').fill('Still interactive');
        assert.equal(await page.locator('#panel-draft').inputValue(), 'Still interactive');
        assert.deepEqual(errors, []);
        console.log('PASS: keyboard selection, focus restoration, inline error, breakpoint state, reduced motion and rapid reopen');
        if (process.env.UI_EVIDENCE_DIR) {
            fs.mkdirSync(process.env.UI_EVIDENCE_DIR, {recursive: true});
            await page.goto(`${process.env.UI_FIXTURE_URL || 'http://127.0.0.1:5129'}/chat?conversation=review`);
            await page.locator('#chat-composer').waitFor();
            await resize({width: 1440, height: 1000});
            await page.waitForTimeout(250);
            await page.screenshot({path: `${process.env.UI_EVIDENCE_DIR}/web-desktop.png`});
            await resize({width: 390, height: 844});
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
            await page.waitForTimeout(250);
            await page.screenshot({path: `${process.env.UI_EVIDENCE_DIR}/web-compact.png`});
            const composer = page.locator('#chat-composer');
            await composer.fill('中文输入');
            assert.equal(await composer.evaluate(e => e.dispatchEvent(new KeyboardEvent('keydown', {key: 'Enter', keyCode: 229, bubbles: true, cancelable: true}))), true);
            await composer.dispatchEvent('compositionstart');
            assert.equal(await composer.evaluate(e => e.dispatchEvent(new KeyboardEvent('keydown', {key: 'Enter', bubbles: true, cancelable: true}))), true);
            await composer.dispatchEvent('compositionend');
            await composer.press('Shift+Enter');
            assert.ok((await composer.inputValue()).includes('\n'));
            await resize({width: 1440, height: 1000});
            await composer.focus();
            await resize({width: 390, height: 844});
            assert.equal(await composer.evaluate(e => e === document.activeElement), true);
            assert.equal(await page.locator('dialog:modal').count(), 0);
            await page.locator('.chat-header [aria-controls="chat-details"]').last().focus();
            await page.keyboard.press('Enter');
            await page.waitForTimeout(250);
            assert.equal(await page.locator('dialog:modal').evaluate(e => e.contains(document.activeElement)), true);
            await page.screenshot({path: `${process.env.UI_EVIDENCE_DIR}/web-inspector-focus.png`});
            await page.keyboard.press('Escape');
            assert.equal(await page.locator('.chat-header [aria-controls="chat-details"]').last().evaluate(e => e === document.activeElement), true);
            await resize({width: 1440, height: 1000});
            await page.locator('.model-menu summary').focus();
            await page.keyboard.press('ArrowDown');
            await page.waitForTimeout(250);
            await page.screenshot({path: `${process.env.UI_EVIDENCE_DIR}/web-model-keyboard.png`});
            console.log('PASS: actual chat IME, Shift+Enter, resize preserves composer focus, modal Escape restores trigger; desktop/compact/menu/inspector screenshots saved');
        }
    } finally { await browser.close(); }
})().catch(e => {console.error(e); process.exitCode = 1;});
