"""Click the standalone prototype in installed Chrome; never call a model or app Store."""
import argparse
import json
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

parser = argparse.ArgumentParser()
parser.add_argument('--url', default='http://127.0.0.1:8067/')
parser.add_argument('--output', default='.artifacts/prototype-redesign-20261024')
args = parser.parse_args()
out = Path(args.output).resolve()
out.mkdir(parents=True, exist_ok=True)
results = []
errors = []

def click(page, name, exact=True):
    page.get_by_role('button', name=name, exact=exact).click()

def shot(page, name):
    page.wait_for_timeout(280)
    page.screenshot(path=str(out / (name+'.png')))
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth'), name+' horizontal overflow'

def check(name):
    results.append(name)
    print('PASS', name, flush=True)

with sync_playwright() as p:
    browser = p.chromium.launch(channel='chrome', headless=True)
    page = browser.new_page(viewport={'width':390,'height':844}, has_touch=True, is_mobile=True)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(args.url)
    expect(page.get_by_role('heading', name='对话',exact=True)).to_be_visible()
    shot(page,'mobile-conversations')
    page.get_by_role('textbox',name='搜索对话').fill('找不到的主题')
    expect(page.get_by_role('heading',name='没有找到这段对话')).to_be_visible()
    page.get_by_role('textbox',name='搜索对话').fill('')
    click(page,'把周末留给山野',False)
    expect(page.locator('#mobile-nav')).to_be_hidden()
    shot(page,'mobile-conversation')
    click(page,'选择模型')
    click(page,'本地模型 · 8B',False)
    expect(page.locator('.mobile-heading')).to_contain_text('本地模型')
    click(page,'对话更多操作')
    shot(page,'mobile-actions')
    click(page,'对话设置',False)
    page.get_by_label('权限策略',exact=True).select_option('按需确认')
    click(page,'保存')
    click(page,'对话更多操作')
    click(page,'对话设置',False)
    expect(page.get_by_label('权限策略',exact=True)).to_have_value('按需确认')
    click(page,'关闭')
    click(page,'回到最新消息')
    click(page,'调整时间')
    page.get_by_label('出发时间',exact=True).select_option('10:30')
    click(page,'保存')
    expect(page.locator('.plan-item').first).to_contain_text('10:30')
    click(page,'保存安排')
    expect(page.get_by_role('button',name='已保存到本段对话')).to_be_visible()
    check('mobile list/search → conversation → model/settings → inline plan update')

    click(page,'返回对话列表')
    click(page,'新对话')
    prompt=page.get_by_role('textbox',name='消息',exact=True)
    prompt.fill('@')
    expect(page.get_by_role('listbox',name='选择专家')).to_be_visible()
    prompt.press('ArrowDown')
    prompt.press('Enter')
    expect(page.locator('#recipient')).to_contain_text('林序')
    expect(page.locator('.message.user')).to_have_count(0)
    prompt.fill('测试草稿需要恢复')
    click(page,'返回对话列表')
    click(page,'新对话')
    expect(prompt).to_have_value('测试草稿需要恢复')
    expect(page.locator('#recipient')).to_contain_text('林序')
    click(page,'发送消息')
    expect(page.locator('#live-reason')).to_be_visible()
    expect(page.locator('#live-text')).not_to_have_text('',timeout=8000)
    expect(page.get_by_role('button',name='停止回复')).to_be_visible()
    shot(page,'mobile-streaming')
    click(page,'停止回复')
    expect(page.get_by_role('button',name='发送消息')).to_be_visible()
    expect(page.get_by_text('已停止 · 已生成内容保留。')).to_have_count(1)
    click(page,'返回对话列表')
    click(page,'新对话')
    expect(prompt).to_have_value('')
    expect(page.locator('#recipient')).to_be_hidden()
    check('mention keyboard selection does not send; draft and recipient restore; stream and stop; new-chat isolation')

    click(page,'返回对话列表')
    click(page,'设置')
    click(page,'专家',False)
    click(page,'新建专家')
    page.get_by_label('名称',exact=True).fill('测试专家')
    page.get_by_label('职责简介',exact=True).fill('整理原型测试发现')
    page.get_by_label('工作指令',exact=True).fill('明确区分结果和未验证项。')
    click(page,'保存')
    click(page,'测试专家',False)
    expect(page.get_by_role('heading',name='测试专家')).to_have_count(2)
    expect(page.get_by_role('textbox',name='消息')).to_have_count(0)
    click(page,'编辑专家')
    page.get_by_label('名称',exact=True).fill('未保存的名字')
    click(page,'关闭')
    expect(page.get_by_text('更改尚未保存。',exact=False)).to_be_visible()
    click(page,'继续编辑')
    expect(page.get_by_label('名称',exact=True)).to_have_value('未保存的名字')
    click(page,'关闭')
    click(page,'丢弃更改')
    expect(page.get_by_role('heading',name='测试专家')).to_have_count(2)
    shot(page,'mobile-expert')
    click(page,'返回')
    click(page,'工作区',True)
    shot(page,'mobile-data')
    click(page,'记忆')
    click(page,'添加记忆')
    page.get_by_label('记忆内容').fill('这是一条测试记忆。')
    click(page,'保存')
    click(page,'这是一条测试记忆。',False)
    click(page,'移除',True)
    click(page,'取消')
    click(page,'这是一条测试记忆。',False)
    click(page,'移除',True)
    click(page,'移除记忆')
    expect(page.get_by_role('button',name='这是一条测试记忆。',exact=False)).to_have_count(0)
    click(page,'资料')
    click(page,'添加资料来源')
    page.get_by_label('名称',exact=True).fill('原型资料')
    click(page,'保存')
    click(page,'原型资料',False)
    click(page,'验证连接')
    expect(page.locator('.kv').filter(has_text='连接状态')).to_contain_text('可用')
    check('expert create and unsaved-edit recovery; no expert chat entry; memory deletion confirmation; source add/detail')

    click(page,'返回')
    click(page,'计划',True)
    shot(page,'mobile-automations')
    click(page,'新建计划')
    page.get_by_label('名称',exact=True).fill('测试计划')
    page.get_by_label('要完成什么').fill('汇总测试结论')
    click(page,'保存')
    click(page,'测试计划',False)
    click(page,'启用')
    expect(page.get_by_role('button',name='暂停',exact=True)).to_be_visible()
    click(page,'试运行')
    expect(page.get_by_text('演示完成 · 没有读取资料或调用模型',exact=True)).to_be_visible()
    click(page,'返回')
    click(page,'设置')
    page.locator('#main [data-action=nav][data-page=models]').click()
    click(page,'添加模型连接')
    page.get_by_label('显示名称').fill('测试连接')
    click(page,'保存')
    click(page,'测试连接',False)
    click(page,'设为默认')
    expect(page.get_by_role('button',name='当前默认',exact=True)).to_be_visible()
    click(page,'返回')
    shot(page,'mobile-models')
    click(page,'设置')
    click(page,'技能与连接',False)
    click(page,'工作区文件',False)
    page.get_by_role('checkbox',name='启用此能力',exact=False).check()
    expect(page.get_by_role('checkbox',name='启用此能力',exact=False)).to_be_checked()
    click(page,'返回')
    click(page,'设置')
    shot(page,'mobile-settings')
    click(page,'外观',False)
    click(page,'深色')
    shot(page,'mobile-settings-dark')
    check('automation create/toggle/run; model add/default; capability toggle; dark theme')

    for scenario in ['需要确认的操作','连接中断与重试','长回复与阅读位置']:
        click(page,'交互场景',False)
        click(page,scenario,False)
        click(page,'对话',True)
        click(page,'新对话')
        prompt.fill('体验'+scenario)
        click(page,'发送消息')
        if scenario=='需要确认的操作':
            expect(page.get_by_text('工作区 / 预算示例.csv',exact=True)).to_be_visible()
            shot(page,'mobile-approval-dark')
            click(page,'不允许')
            expect(page.get_by_text('未读取文件。',exact=False)).to_be_visible()
        elif scenario=='连接中断与重试':
            shot(page,'mobile-error-dark')
            click(page,'重试')
            expect(page.get_by_role('button',name='停止回复')).to_be_visible()
            click(page,'停止回复')
            expect(page.locator('.message.user')).to_have_count(1)
        else:
            page.wait_for_function("document.querySelector('#transcript').scrollHeight-document.querySelector('#transcript').clientHeight>800")
            page.locator('#transcript').hover()
            page.mouse.wheel(0,-1800)
            page.wait_for_timeout(500)
            before=page.locator('#transcript').evaluate('(el)=>el.scrollTop')
            page.wait_for_timeout(600)
            after=page.locator('#transcript').evaluate('(el)=>el.scrollTop')
            assert abs(after-before)<10,(before,after)
            expect(page.get_by_role('button',name='回到最新消息')).to_be_visible()
            click(page,'回到最新消息')
            page.wait_for_timeout(500)
            expect(page.get_by_role('button',name='回到最新消息')).to_be_hidden()
            shot(page,'mobile-long-dark')
            if page.get_by_role('button',name='停止回复').count():click(page,'停止回复')
        click(page,'返回对话列表')
        click(page,'设置')
    check('approval reject; retry preserves one request; long streaming preserves reading anchor and latest navigation')
    assert not errors,errors
    page.close()

    for name,w,h,theme in [('desktop',1440,960,'light'),('desktop-dark',1440,960,'dark'),('tablet',820,1180,'light'),('small',320,640,'light'),('short-viewport',390,420,'light'),('mobile-dark',390,844,'dark')]:
        page=browser.new_page(viewport={'width':w,'height':h},color_scheme=theme)
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(args.url)
        shot(page,name+'-initial')
        if w<=760:click(page,'把周末留给山野',False)
        shot(page,name+'-chat')
        if w<=760:
            small=page.locator('button').evaluate_all("els=>els.filter(e=>{const r=e.getBoundingClientRect();return r.width>0&&r.height>0&&(r.width<43.5||r.height<43.5)}).map(e=>e.outerHTML)")
            assert not small,small
        click(page,'对话更多操作')
        shot(page,name+'-menu')
        expect(page.get_by_role('button',name='关闭',exact=True)).to_be_in_viewport()
        page.keyboard.press('Escape')
        expect(page.get_by_role('dialog')).to_be_hidden()
        expect(page.get_by_role('button',name='对话更多操作')).to_be_focused()
        if w>760:
            for target in ['工作区','专家','模型','技能与连接','设置']:
                click(page,target,True)
                shot(page,name+'-'+{'工作区':'workspace','专家':'experts','模型':'models','技能与连接':'skills','设置':'settings'}[target])
        page.close()
    check('320/390/820/1440 layouts; light/dark screens; modal dismissal restores focus; all desktop modules')
    assert not errors,errors
    browser.close()
(out/'verification.json').write_text(json.dumps({'passed':results,'browser_errors':errors,'scope':'Standalone prototype; fictional data; no model or production application tests.'},ensure_ascii=False,indent=2))
