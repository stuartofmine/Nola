"""Derive native template assets from assets/icons, the single SVG source.

Geometry is drawn in the v23 prototype's 24-unit grid: 1.55-unit rounded strokes.
Run after editing an SVG. Web imports these source SVGs directly.
"""
import json
from pathlib import Path
from xml.etree import ElementTree as ET

root = Path(__file__).resolve().parent.parent
for source in sorted((root / "assets/icons").glob("*.svg")):
    svg = source.read_text()
    node = ET.fromstring(svg)
    name = source.stem
    for app in ("apps/ios", "apps/macos"):
        folder = root / app / "Assets.xcassets" / f"nola-{name}.imageset"
        folder.mkdir(exist_ok=True)
        (folder / f"{name}.svg").write_text(svg.replace("currentColor", "#000000"))
        (folder / "Contents.json").write_text(json.dumps({
            "images": [{"filename": f"{name}.svg", "idiom": "universal"}],
            "info": {"author": "xcode", "version": 1},
            "properties": {"preserves-vector-representation": True,
                           "template-rendering-intent": "template"},
        }, indent=2) + "\n")
    paths = "\n".join(
        f'    <path android:pathData="{path.attrib["d"]}" '
        'android:fillColor="@android:color/transparent" android:strokeColor="#FF000000" '
        'android:strokeWidth="1.55" android:strokeLineCap="round" android:strokeLineJoin="round"/>'
        for path in node
    )
    target = root / "apps/android/app/src/main/res/drawable" / f"nola_{name}.xml"
    target.write_text('<!-- Generated by scripts/generate_ui_icons.py; edit assets/icons. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android" '
        'android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'
        + paths + "\n</vector>\n")

# The standalone prototype consumes the same geometry without importing a renderer.
prototype_paths = {
    source.stem: " ".join(path.attrib["d"] for path in ET.fromstring(source.read_text()))
    for source in sorted((root / "assets/icons").glob("*.svg"))
}
(root / "docs/design/prototype/shared-icons.js").write_text(
    "// Generated by scripts/generate_ui_icons.py; edit assets/icons.\n"
    + "window.nolaIconPaths=" + json.dumps(prototype_paths, ensure_ascii=False, sort_keys=True) + ";\n"
)
