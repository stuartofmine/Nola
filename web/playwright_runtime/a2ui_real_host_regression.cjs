// Explicit isolated real Host only. No route mocks; credentials remain in memory.
const { chromium } = require('playwright-core');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
    const state = JSON.parse(fs.readFileSync('/tmp/nola-a2ui-real-host-state.json','utf8'));
    const conversation = process.env.NOLA_A2UI_TEST_CONVERSATION;
    assert.ok(conversation, 'explicit isolated conversation is required');
    const entry = new URL(state.url);
    assert.equal(entry.hostname, '127.0.0.1'); assert.equal(entry.port, '5141');
    const out = '/tmp/nola-a2ui-real-chrome'; fs.mkdirSync(out,{recursive:true});
    const browser = await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
    const context = await browser.newContext({viewport:{width:1280,height:900}});
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', error => errors.push(error.name));
    let configurationRequests = 0;
    page.on('request', request => { if (new URL(request.url()).pathname.endsWith('/configuration')) configurationRequests++; });
    try {
        await page.goto(state.url);
        await page.goto(`${entry.origin}/chat?conversation=${encodeURIComponent(conversation)}`);
        const surface = page.locator('.surface-reference').first();
        await surface.waitFor({timeout:60000});
        const field = surface.locator('input:not([disabled]),textarea:not([disabled])').first();
        await field.waitFor({timeout:30000});
        configurationRequests = 0;
        await page.waitForTimeout(3000);
        assert.ok(configurationRequests <= 7, 'permission polling must not restart after every response');
        const beforeMessages = await page.evaluate(async id => (await fetch(`/api/chat/conversations/${encodeURIComponent(id)}/messages`)).json(), conversation);
        fs.writeFileSync(out+'/messages-before.json', JSON.stringify(beforeMessages,null,2));
        await field.fill('真实浏览器验证第二次');
        await page.screenshot({path:out+'/edited.png'});
        const responsePromise = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/ui-interactions'),{timeout:30000});
        await surface.locator('button.a2ui-button:not([disabled])').first().click();
        const response = await responsePromise; const result = await response.json();
        fs.writeFileSync(out+'/receipt.json',JSON.stringify(result,null,2));
        fs.writeFileSync(out+'/request.json',JSON.stringify(response.request().postDataJSON(),null,2));
        assert.equal(response.status(),200); assert.equal(result.status,'committed');
        assert.ok(result.receipt?.queued_submission_id, 'button action must enqueue an Agent input');
        assert.ok(result.receipt?.snapshot?.revision > 1);
        await page.reload(); await surface.waitFor({timeout:30000});
        await surface.getByRole('button',{name:/查看此版本/}).click();
        const history = surface.getByRole('region',{name:'此版本的只读表单'});
        await history.waitFor();
        await page.waitForFunction(() => document.querySelector('section[aria-label="此版本的只读表单"]')?.getAttribute('aria-busy') === 'false');
        assert.equal(await history.locator('input:not([disabled]),textarea:not([disabled]),button.a2ui-button:not([disabled])').count(),0);
        await page.screenshot({path:out+'/history.png'});
        await page.setViewportSize({width:390,height:844});
        await surface.evaluate(element => element.scrollIntoView({block:'start'}));
        await page.screenshot({path:out+'/mobile.png'});
        const afterMessages = await page.evaluate(async id => (await fetch(`/api/chat/conversations/${encodeURIComponent(id)}/messages`)).json(), conversation);
        fs.writeFileSync(out+'/messages-after.json', JSON.stringify(afterMessages,null,2));
        assert.deepEqual(errors,[]);
        fs.writeFileSync(out+'/result.json',JSON.stringify({kind:'real-host-real-model',conversation,committedRevision:result.receipt.snapshot.revision,passed:['render','edit','submit','reload','historical-read-only','mobile-render'],pageErrors:errors},null,2));
        console.log('PASS real Host Chrome A2UI');
    } catch (error) {
        await page.screenshot({path:out+'/failure.png'}).catch(()=>{});
        console.error('Real Host Chrome failure:',String(error.message).replace(/https?:\/\/[^\s"']+/g,'[URL]'));
        process.exitCode=1;
    } finally { await browser.close(); }
})().catch(error=>{ console.error('Real Host test initialization failed:',error.name); process.exitCode=1; });
